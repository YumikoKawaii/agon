use macroquad::math::Vec2;

use crate::core::effect::EffectKind;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Element {
    Frost,
    Holy,
    Blade,
    Hex,
    Spirit,
    Arcane,
}

#[derive(Clone, Copy, Debug)]
pub enum Event {
    Needle { tip: Vec2, ang: f32 },
    Ward { pos: Vec2, front: Vec2 },
    Blocked { pos: Vec2 },
    RayFired { origin: Vec2, dir: Vec2 },
    JudgeCast { caster: Vec2, at: Vec2 },
    JudgeStrike { pos: Vec2 },
    Cut { owner: usize, ang: f32, r: f32, half: f32, side: f32, big: bool },
    Swallow { pos: Vec2, dir: Vec2 },
    SwallowHit { tip: Vec2 },
    Intent { pos: Vec2, dir: Vec2 },
    IntentFade { pos: Vec2, dir: Vec2 },
    Wind { from: Vec2, to: Vec2, dir: Vec2 },
    Ghost { seat: usize, pos: Vec2, ang: f32, life: f32 },
    FormCast { caster: Vec2, center: Vec2 },
    FormBurst { center: Vec2, base: f32 },
    HexCast { tip: Vec2 },
    PotionBurst { pos: Vec2 },
    Broom { from: Vec2, to: Vec2, dir: Vec2 },
    CauldronCast { caster: Vec2, at: Vec2 },
    CauldronBurst { pos: Vec2 },
    Hit { pos: Vec2, element: Element, dmg: i32, big: bool },
    Status { pos: Vec2, kind: EffectKind },
    Dot { pos: Vec2, kind: EffectKind, dmg: i32 },
    Absorb { pos: Vec2, amount: i32 },
    MarkPop { pos: Vec2 },
    BleedPop { pos: Vec2, dmg: i32 },
    TalismanCast { tip: Vec2, dir: Vec2 },
    ParasolThrow { from: Vec2, to: Vec2 },
    ParasolPlant { pos: Vec2 },
    ParasolPickup { pos: Vec2 },
    StormCast { caster: Vec2, at: Vec2 },
    StormTick,
    StormBurst { pos: Vec2 },
    SpiritStep { from: Vec2, to: Vec2, ang: f32 },
    FoxCast { tip: Vec2, dir: Vec2 },
    FoxBlast { pos: Vec2 },
    FoxStrike { pos: Vec2 },
    FoxSwipe { pos: Vec2, ang: f32, big: bool },
    FoxDash { from: Vec2, to: Vec2 },
    FoxPoof { pos: Vec2 },
    PetalDash { from: Vec2, to: Vec2, ang: f32 },
    Blossom { pos: Vec2 },
    SerenShot { tip: Vec2, dir: Vec2 },
    SerenBlast { pos: Vec2, big: bool },
    SerenTransform { pos: Vec2, over: bool },
    SerenPunch { pos: Vec2, ang: f32, big: bool, lit: bool },
    SerenLance { origin: Vec2, dir: Vec2, big: bool, hit: Option<Vec2> },
    SerenWell { pos: Vec2 },
    SerenPop { pos: Vec2 },
    SerenFists { pos: Vec2 },
    SerenDash { from: Vec2, to: Vec2 },
    SerenCharge { pos: Vec2 },
    SerenBeam { origin: Vec2, dir: Vec2, over: bool },
    SerenFull { pos: Vec2 },
}
