CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(16) NOT NULL,
    password_hash VARCHAR(72) NOT NULL,
    kit INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX idx_users_name ON users (lower(name));

CREATE TABLE rooms (
    id CHAR(6) PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    guest_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    host_ready BOOLEAN NOT NULL DEFAULT FALSE,
    guest_ready BOOLEAN NOT NULL DEFAULT FALSE,
    state INT NOT NULL DEFAULT 1,
    match_id VARCHAR(16) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);

CREATE TABLE matches (
    id VARCHAR(16) PRIMARY KEY,
    room_id CHAR(6) NOT NULL,
    host_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    guest_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    winner_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    host_deaths INT NOT NULL DEFAULT 0,
    guest_deaths INT NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    ended_at TIMESTAMPTZ(3) NULL
);

CREATE INDEX idx_matches_room ON matches (room_id);
